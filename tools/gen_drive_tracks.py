"""Generates engine/sim/objects/drive_tracks.inc from re/data/drive_tracks.json.

Run: python tools/gen_drive_tracks.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
d = json.loads((ROOT / "re" / "data" / "drive_tracks.json").read_text())
lines = ["// Generated by tools/gen_drive_tracks.py from re/data/drive_tracks.json. Do not edit.",
         "// DriveLocomotionClass tracks: RawTrack[16] (0x7E7A28) and TurnTrack[72] (0x7E7B28)."]
for i in range(1, 16):
    pts = d["raw_tracks"][str(i)]["points"]
    lines.append("static const Point kTrack%d[] = { %s };" % (i, ", ".join("{ %d, %d, %d }" % tuple(p) for p in pts)))
lines.append("static const RawTrack kRawTracks[16] = {")
lines.append("\t{ -1, 0, -1, nullptr, 0 },")
for i in range(1, 16):
    t = d["raw_tracks"][str(i)]
    lines.append("\t{ %d, %d, %d, kTrack%d, %d }," % (t["jump"], t["entry"], t["cell"], i, len(t["points"])))
lines.append("};")
lines.append("static const TurnTrack kTurnTracks[72] = {")
for t in d["turn_track"]:
    lines.append("\t{ %d, %d, %d, %d }," % (t["track"], t["start_track"], t["facing"], t["flag"]))
lines.append("};")
out = ROOT / "engine" / "sim" / "objects" / "drive_tracks.inc"
out.write_text("\n".join(lines) + "\n", newline="\n")
print("wrote", out)
