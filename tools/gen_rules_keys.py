"""Generates engine/rules/key_table_data.inc from re/data/ini_keys.tsv.

The TSV lists every INI key the original game reads, with the type of its
reader, the class that reads it, the section it lives in and the built-in default
(see the reverse-engineering notes on rule defaults). The engine uses the table to
read rules by key with the correct type and the original's default.

Normalisation of the "default" column:
- "(none)"                            -> an empty-string default
- "(current value)", "(ini-supplied)", "(map-supplied)", or a default that came from a
  register and isn't a literal (an address, not a value) -> no known default
- a denormal double (uninitialised memory) -> no known default
- anything else                       -> that literal text (two bool defaults are expressions of
                                         other keys: "!NoRotate" and "SpeedType==Float")

Run: python tools/gen_rules_keys.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "re" / "data" / "ini_keys.tsv"
OUT = ROOT / "engine" / "rules" / "key_table_data.inc"

TYPES = {
    "int": "Int", "bool": "Bool", "string": "String", "double": "Double", "typelist": "TypeList",
    "leptons": "Leptons", "rgb": "Rgb", "movie": "Movie", "infantrylist": "InfantryList", "house": "House",
    "buildingtypelist": "BuildingTypeList", "buildinglist": "BuildingList", "type": "Type", "rect": "Rect",
    "colorscheme": "ColorScheme", "theater": "Theater", "soundlist": "SoundList", "unitlist": "UnitList",
    "technolist": "TechnoList", "housebits": "HouseBits", "armor": "Armor", "aircraftlist": "AircraftList",
}


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = list(csv.DictReader(SRC.open(encoding="utf-8"), delimiter="\t"))
    entries = []
    seen = set()
    for r in rows:
        key, section, owner, typ = r["key"], r["section"], r["class"], r["type"]
        if typ not in TYPES:
            raise SystemExit(f"unknown type {typ!r} for {key}")
        default = r["default"]
        source = r["default_source"]
        has_default = True
        if default.startswith("("):
            has_default = default == "(none)"
            default = ""
        elif source.split(" ")[0] in ("reg", "uninit"):
            # A register-passed or uninitialised "default" is an address or garbage, not a value.
            has_default = False
            default = ""
        if typ == "double" and has_default and default:
            try:
                if 0.0 < abs(float(default)) < 1e-300:
                    # A denormal "default" is uninitialised memory, not a value.
                    has_default, default = False, ""
            except ValueError:
                pass
        ident = (owner, key.lower(), section)
        if ident in seen:
            continue  # the same read found twice; keep the first
        seen.add(ident)
        entries.append((owner, key, section, TYPES[typ], default, has_default))
    entries.sort(key=lambda e: (e[0], e[1].lower()))

    lines = ["// Generated by tools/gen_rules_keys.py from re/data/ini_keys.tsv. Do not edit.",
             "// owner class, key, section, type, default text, has default"]
    for owner, key, section, typ, default, has in entries:
        lines.append(f"{{ {c_string(owner)}, {c_string(key)}, {c_string(section)}, KeyType::{typ}, {c_string(default)}, {'true' if has else 'false'} }},")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", newline="\n", encoding="utf-8")
    print(f"wrote {len(entries)} keys to {OUT}")


if __name__ == "__main__":
    main()
