"""Generates engine/sim/loop/event_lengths.inc from re/data/event_lengths.tsv.

Run: python tools/gen_event_lengths.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = [l.split("\t") for l in (ROOT / "re" / "data" / "event_lengths.tsv").read_text().splitlines()[1:] if l.strip()]
lines = ["// Generated by tools/gen_event_lengths.py from re/data/event_lengths.tsv. Do not edit.",
         "// { name, payload bytes } per event type (table at 0x8208EC)."]
for i, (num, name, size) in enumerate(rows):
    assert int(num) == i
    lines.append('{ "%s", %d },' % (name.strip(), int(size)))
out = ROOT / "engine" / "sim" / "loop" / "event_lengths.inc"
out.write_text("\n".join(lines) + "\n", newline="\n")
print(f"wrote {len(rows)} event types to {out}")
