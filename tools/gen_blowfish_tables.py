"""Generates engine/vfs/blowfish_tables.inc.

Blowfish's initial P-array (18 words) and S-boxes (4 x 256 words) are the
first 1042 32-bit words of the fractional part of pi. This script computes pi
to enough digits with Machin's formula and writes the words.

Run: python tools/gen_blowfish_tables.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "engine" / "vfs" / "blowfish_tables.inc"
WORDS = 18 + 4 * 256


def arccot(x: int, one: int) -> int:
    """arccot(x) scaled by `one`, via the Taylor series."""
    total = term = one // x
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        n += 2
        total += sign * (term // n)
        sign = -sign
    return total


def pi_fraction_words(count: int) -> list[int]:
    bits = count * 32 + 64  # guard bits
    one = 1 << bits
    pi = 4 * (4 * arccot(5, one) - arccot(239, one))  # Machin
    frac = pi - 3 * one
    words = []
    for i in range(count):
        words.append((frac >> (bits - 32 * (i + 1))) & 0xFFFFFFFF)
    return words


def main():
    w = pi_fraction_words(WORDS)
    assert w[0] == 0x243F6A88 and w[1] == 0x85A308D3 and w[18] == 0xD1310BA6, "pi digits wrong"
    lines = ["// Generated by tools/gen_blowfish_tables.py. Do not edit.",
             "// Blowfish initial state: the fractional hex digits of pi."]

    def emit(name, vals):
        lines.append(f"static const uint32_t {name}[{len(vals)}] = {{")
        for i in range(0, len(vals), 8):
            lines.append("\t" + ", ".join(f"0x{v:08X}u" for v in vals[i:i + 8]) + ",")
        lines.append("};")

    emit("kInitP", w[:18])
    for s in range(4):
        emit(f"kInitS{s}", w[18 + 256 * s:18 + 256 * (s + 1)])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
