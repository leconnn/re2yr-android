"""Generates engine/sim/world/slope_planes.inc from re/data/slope_planes.json.

Run: python tools/gen_slope_planes.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
planes = json.loads((ROOT / "re" / "data" / "slope_planes.json").read_text())["planes"]
lines = ["// Generated by tools/gen_slope_planes.py from re/data/slope_planes.json. Do not edit.",
         "// A, B, C, Max, D of the 20 ramp planes (SlopeIndex 1..20)."]
for p in planes:
    lines.append("{ %s, %s, %s, %s, %s }," % tuple(repr(float(p[k])) for k in ("A", "B", "C", "Max", "D")))
out = ROOT / "engine" / "sim" / "world" / "slope_planes.inc"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n", newline="\n")
print(f"wrote {len(planes)} planes to {out}")
