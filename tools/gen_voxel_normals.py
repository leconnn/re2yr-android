"""Generates engine/voxel/voxel_normals.inc from re/data/voxel_normal_sets.json.

Run: python tools/gen_voxel_normals.py
"""
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sets = json.loads((ROOT / "re" / "data" / "voxel_normal_sets.json").read_text())


def f32(v):
    return repr(struct.unpack("<f", struct.pack("<f", v))[0]) + "f"


lines = ["// Generated by tools/gen_voxel_normals.py from re/data/voxel_normal_sets.json. Do not edit.",
         "// The unit normals of the voxel normal sets, indexed by a section's normal mode (1..4)."]
for mode in ("1", "2", "3", "4"):
    normals = sets[mode]
    lines.append("// mode %s: %d normals" % (mode, len(normals)))
    lines.append("static const float kNormalSet%s[][3] = {" % mode)
    for n in normals:
        lines.append("\t{ %s, %s, %s }," % tuple(f32(c) for c in n))
    lines.append("};")
out = ROOT / "engine" / "voxel" / "voxel_normals.inc"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n", newline="\n")
print("wrote", out)
