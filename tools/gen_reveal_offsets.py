"""Generates engine/sim/world/reveal_offsets.inc from re/data/reveal_offsets.json.

Run: python tools/gen_reveal_offsets.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "re" / "data" / "reveal_offsets.json").read_text())
offsets = data["offsets"]
los = data["los_offsets_abcf60"]
lines = ["// Generated by tools/gen_reveal_offsets.py from re/data/reveal_offsets.json. Do not edit.",
         "// MapClass reveal offsets (0xABD490): (dx, dy). Radius r uses the first kRevealCount[r] entries."]
lines += ["{ %d, %d }," % (dx, dy) for dx, dy in offsets]
out = ROOT / "engine" / "sim" / "world" / "reveal_offsets.inc"
out.write_text("\n".join(lines) + "\n", newline="\n")
print(f"wrote {len(offsets)} offsets to {out}")

lines = ["// Generated by tools/gen_reveal_offsets.py from re/data/reveal_offsets.json. Do not edit.",
         "// The per-entry line of sight steps (0xABCF60), used with RevealByHeight."]
# Entries the original never writes stay zero (the table lives in zero-initialised memory).
lines += ["{ %d, %d }," % tuple(e if e is not None else (0, 0)) for e in los]
out = ROOT / "engine" / "sim" / "world" / "reveal_los.inc"
out.write_text("\n".join(lines) + "\n", newline="\n")
print(f"wrote {len(los)} line of sight steps to {out}")
