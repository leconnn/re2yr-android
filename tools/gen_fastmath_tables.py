"""Generates engine/core/fastmath_tables.inc.

The original game's maths functions (sqrt, sin, cos, tan, asin, acos, atan,
atan2) are table lookups. The tables hold float values computed in the
game's x87 mode: round toward zero, then stored as 32-bit floats. This script
recomputes them from their formulas. tests/core/fastmath_test.cpp checks each
table against a checksum of the original, so any platform difference in the
maths library is caught.

Run: python tools/gen_fastmath_tables.py
"""
import math
import struct
from fractions import Fraction
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "engine" / "core" / "fastmath_tables.inc"


def f32_bits(x: float) -> int:
    return struct.unpack("<I", struct.pack("<f", x))[0]


def to_float_rz(x: float) -> float:
    """Round a double to a 32-bit float toward zero."""
    f = struct.unpack("<f", struct.pack("<f", x))[0] if math.isfinite(x) and abs(x) < 3.4e38 else x
    if f != 0.0 and math.isfinite(f) and abs(f) > abs(x):
        bits = f32_bits(f) - 1  # one step toward zero (same sign)
        f = struct.unpack("<f", struct.pack("<I", bits))[0]
    return f


def add_rz(a: float, b: float) -> float:
    """Double addition rounded toward zero."""
    exact = Fraction(a) + Fraction(b)
    r = float(exact)
    if Fraction(r) != exact and abs(Fraction(r)) > abs(exact):
        r = math.nextafter(r, 0.0)
    return r


def sin_table():
    # 8192 steps per turn, plus a quarter turn so cos can share it, plus one guard entry.
    t = [f32_bits(to_float_rz(math.sin(i * (2.0 * math.pi / 8192.0)))) for i in range(0x2801)]
    # Exact multiples of pi: the original used the x87 fsin instruction, whose
    # 66-bit internal pi gives slightly different tiny results there.
    t[4096] = 0x250D3000   # x87 fsin(pi)  = 1.2246063538223773e-16
    t[8192] = 0xA58D3000   # x87 fsin(2pi) = -2.4492127076447545e-16
    return t


def tan_table():
    t = [f32_bits(to_float_rz(math.tan(i * (2.0 * math.pi / 4096.0)))) for i in range(4097)]
    t[1024] = 0x5A6816AA   # x87 fptan(pi/2)  = 1.6331778499280896e16
    t[2048] = 0xA50D3000   # x87 fptan(pi)    = -1.2246063538223773e-16
    t[3072] = 0x599AB9C6   # x87 fptan(3pi/2) = 5443925808513024
    t[4096] = 0xA58D3000   # x87 fptan(2pi) (guard entry, never indexed)
    return t


def asin_table():
    return [f32_bits(to_float_rz(math.asin(k / 2048.0 - 1.0))) for k in range(4097)]


def atan_table():
    # x advances by a float step, truncated to float after every addition.
    step = struct.unpack("<f", struct.pack("<f", 0.024413354694843292))[0]
    x = 0.0
    t = []
    for _ in range(4097):
        t.append(f32_bits(to_float_rz(math.atan(x))))
        x = to_float_rz(add_rz(x, step))
    return t


def sqrt_table():
    # Indexed by 13 mantissa bits plus "exponent is odd": stores the mantissa
    # bits of sqrt(mantissa) or sqrt(2 * mantissa), relative to 1.0f.
    t = []
    for j in range(16384):
        x = (1.0 + (j & 8191) / 8192.0) * (2.0 if j >= 8192 else 1.0)
        t.append((f32_bits(to_float_rz(math.sqrt(x))) - 0x3F800000) & 0xFFFFFFFF)
    return t


def emit(name, values, comment):
    lines = [f"// {comment}", f"alignas(64) static const uint32_t {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 8):
        lines.append("\t" + ", ".join(f"0x{v:08X}" for v in values[i:i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "// Generated by tools/gen_fastmath_tables.py. Do not edit.",
        "// Float bit patterns of the original game's maths lookup tables.",
        "",
        emit("kSinTable", sin_table(), "sin(i * 2pi / 8192), i = 0..0x2800 (cos reads it 0x800 entries later)"),
        "",
        emit("kTanTable", tan_table(), "tan(i * 2pi / 4096), i = 0..4096"),
        "",
        emit("kAsinTable", asin_table(), "asin(k / 2048 - 1), k = 0..4096"),
        "",
        emit("kAtanTable", atan_table(), "atan(x_i), x advancing by 0.0244133547f, i = 0..4096"),
        "",
        emit("kSqrtTable", sqrt_table(), "mantissa bits of sqrt(m) for 13-bit mantissas, even then odd exponent"),
        "",
    ]
    OUT.write_text("\n".join(parts), newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
